import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { COW_RIG_PARTS } from '../src/assets/cow-workspace/rig.ts';
import {
  COMPLETE_COW_PROPS,
  COMPLETE_COW_PROP_VIEWBOX,
} from '../src/assets/cow-workspace/complete-props.ts';
import {
  COW_GLOBE_ROTATION_BASE,
  COW_GLOBE_ROTATION_DURATION,
  COW_GLOBE_ROTATION_FRAMES,
  COW_GLOBE_ROTATION_OVERLAY,
} from '../src/assets/cow-workspace/globe-rotation.ts';

const directory = new URL('../src/assets/cow-workspace/', import.meta.url);
const spritePath = new URL('scene-sprite.svg', directory);
const metadataPath = new URL('scene-metadata.ts', directory);
const animationPath = new URL('scene-globe-animation.css', directory);
const attributes = new Set(['fill', 'd', 'opacity', 'transform']);

/** Preserve the source geometry and materials verbatim in an external SVG group. */
function pathMarkup(path) {
  if (typeof path.fill !== 'string' || typeof path.d !== 'string')
    throw new Error('A cow sprite path must contain fill and d.');
  const escape = (value) =>
    String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
  const serialized = Object.entries(path).map(([name, value]) => {
    if (!attributes.has(name)) throw new Error(`Unsupported cow sprite attribute: ${name}`);
    if (name === 'opacity' ? !Number.isFinite(value) : typeof value !== 'string')
      throw new Error(`Invalid cow sprite attribute: ${name}`);
    return `${name}="${escape(value)}"`;
  });
  return `<path ${serialized.join(' ')}/>`;
}

/** All React transforms and animation classes remain outside these immutable groups. */
export async function cowSceneSpriteArtifacts() {
  const groups = [];
  let pathCount = 0;
  const group = (id, paths) => {
    pathCount += paths.length;
    groups.push(`<g id="${id}">${paths.map(pathMarkup).join('')}</g>`);
    return id;
  };
  const rigIds = Object.fromEntries(
    Object.entries(COW_RIG_PARTS).map(([name, paths]) => [name, group(`rig-${name}`, paths)]),
  );
  const propIds = Object.fromEntries(
    Object.entries(COMPLETE_COW_PROPS)
      .filter(([name]) => name !== 'deskContactShadows')
      .map(([name, paths]) => [name, group(`prop-${name}`, paths)]),
  );
  const baseId = group('globe-base', COW_GLOBE_ROTATION_BASE);
  const frames = COW_GLOBE_ROTATION_FRAMES.map(({ angle, paths }, index) => ({
    angle,
    id: group(`globe-frame-${index}`, paths),
  }));
  const overlayId = group('globe-overlay', COW_GLOBE_ROTATION_OVERLAY);
  const sprite =
    `<!-- Generated by scripts/build-cow-scene-sprite.mjs; exact source vector paths. -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${COMPLETE_COW_PROP_VIEWBOX}" shape-rendering="crispEdges">\n` +
    `<defs>\n${groups.join('\n')}\n</defs>\n</svg>\n`;
  const declaration = (name, value) =>
    `export const ${name} = ${JSON.stringify(value)} as const;\n`;
  const metadata = await format(
    '/** Generated by scripts/build-cow-scene-sprite.mjs; no drawing paths enter JavaScript. */\n' +
      declaration('COW_RIG_PART_IDS', rigIds) +
      declaration('COMPLETE_COW_PROP_IDS', propIds) +
      declaration('COMPLETE_COW_PROP_VIEWBOX', COMPLETE_COW_PROP_VIEWBOX) +
      declaration('COW_GLOBE_ROTATION_BASE_ID', baseId) +
      declaration('COW_GLOBE_ROTATION_DURATION', COW_GLOBE_ROTATION_DURATION) +
      declaration('COW_GLOBE_ROTATION_FRAMES', frames) +
      declaration('COW_GLOBE_ROTATION_OVERLAY_ID', overlayId),
    { ...(await resolveConfig(fileURLToPath(metadataPath))), parser: 'typescript' },
  );
  // One visible interval, offset per frame, replaces 120 almost identical rules.
  const animation = await format(
    '/* Generated by scripts/build-cow-scene-sprite.mjs; one interval per globe frame. */\n' +
      `@keyframes cow-globe-turn {0% {opacity: 1;} ${(100 / frames.length).toFixed(8)}%, 100% {opacity: 0;}}`,
    { ...(await resolveConfig(fileURLToPath(animationPath))), parser: 'css' },
  );
  return { sprite, metadata, animation, groupCount: groups.length, pathCount };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { sprite, metadata, animation, groupCount, pathCount } = await cowSceneSpriteArtifacts();
  if (process.argv.includes('--check')) {
    const [currentSprite, currentMetadata, currentAnimation] = await Promise.all([
      readFile(spritePath, 'utf8'),
      readFile(metadataPath, 'utf8'),
      readFile(animationPath, 'utf8'),
    ]);
    if (currentSprite !== sprite || currentMetadata !== metadata || currentAnimation !== animation)
      throw new Error('Cow scene sprite is stale. Run node scripts/build-cow-scene-sprite.mjs.');
    console.log(
      `Cow scene sprite verified: ${groupCount} groups, ${pathCount} exact vector paths.`,
    );
  } else {
    await Promise.all([
      writeFile(spritePath, sprite),
      writeFile(metadataPath, metadata),
      writeFile(animationPath, animation),
    ]);
    console.log(`Cow scene sprite generated: ${groupCount} groups, ${pathCount} vector paths.`);
  }
}
